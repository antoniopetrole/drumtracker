local t = require("harness")
local T = require("timing")

t.test("hit time advances per sample from the block position", function()
  t.near(T.hit_seconds(10, 0, 48000), 10)
  t.near(T.hit_seconds(10, 480, 48000), 10.01)
end)

t.test("hit QN uses tempo: 480 samples at 48k and 120 BPM is 0.02 QN", function()
  t.near(T.hit_qn(8, 480, 120, 48000), 8.02)
end)

t.test("sign convention: late is positive, early is negative", function()
  t.near(T.signed_error_ms(0.515, 0.500), 15, 1e-9)
  t.near(T.signed_error_ms(0.480, 0.500), -20, 1e-9)
end)

t.test("calibration subtracts from the signed error", function()
  t.near(T.corrected_error_ms(25, 10), 15)
  t.near(T.corrected_error_ms(-5, 10), -15)
end)

t.test("120 BPM grid: bar 2000 ms, kick 0/1000, snare 500/1500, hat 250", function()
  local q = T.linear_qn_to_time(120)
  t.near(q(4), 2.0)
  t.near(q(2), 1.0)
  t.near(q(1), 0.5)
  t.near(q(3), 1.5)
  t.near(q(0.5) - q(0), 0.25)
end)

t.test("format keeps an explicit sign", function()
  t.eq(T.format_ms(14.2), "+14 ms")
  t.eq(T.format_ms(-9.4), "-9 ms")
  t.eq(T.format_ms(0.2), "0 ms")
  t.eq(T.format_ms(-0.2), "0 ms")
end)

t.test("classify uses the on-time band", function()
  t.eq(T.classify(14, 5), "LATE")
  t.eq(T.classify(-9, 5), "EARLY")
  t.eq(T.classify(3, 5), "ON TIME")
end)

t.test("project check refuses meters and tempo changes rather than guessing", function()
  t.truthy(T.check_project_map(120, 4, 4, {}))
  t.truthy(T.check_project_map(120, 4, 4, { { bpm = 120, ts_num = 4, ts_denom = 4 } }))
  t.eq((T.check_project_map(120, 3, 4, {})), false)
  t.eq((T.check_project_map(120, 4, 4, { { bpm = 90, ts_num = 0, ts_denom = 0 } })), false)
  t.eq((T.check_project_map(120, 4, 4, { { bpm = 120, ts_num = 7, ts_denom = 8 } })), false)
end)
